// Copies the booking app's Privacy Notice into this site, so micromobility.sa/privacy and the
// booking app always say the same thing. The booking app owns the text (app.src.html in
// MicromobilityRentalsSystem: PRIVACY_VERSION, _PV_MAIL, PRIVACY_NOTICE). It also copies the
// app's nationality list and Arabic country names (NATIONALITIES, COUNTRY_AR) into
// src/content/nationalities.ts: the Learn to ride sign-up asks a nationality, which becomes the
// account's, so it must be one of the app's. And its calling codes (COUNTRY_CODES) into
// src/content/dial-codes.ts: the emergency contact's mobile number is asked with a dial code
// (2026-10-07), from the app's own list. Run after any of them changes:
//   node scripts/sync-privacy-notice.mjs ../../../micromobilityrentals/app.src.html
import fs from "node:fs";
import vm from "node:vm";

const src = fs.readFileSync(process.argv[2] || "", "utf8");
const from = src.indexOf("const PRIVACY_VERSION=");
const to = src.indexOf("function _privacyBody", from);
if (from < 0 || to < 0) throw new Error("PRIVACY_NOTICE not found in " + process.argv[2]);
const code = src.slice(from, to).replace(/\bconst\b/g, "var");
const ctx = {};
vm.runInNewContext(code, ctx);
const { PRIVACY_VERSION: version, PRIVACY_NOTICE: notice } = ctx;
// The last version riders must confirm (the booking app's PRIVACY_ASK_FROM; older apps: the notice's own date).
const askFrom = ctx.PRIVACY_ASK_FROM || version;
if (!/^\d{4}-\d{2}-\d{2}$/.test(ctx.PRIVACY_ASK_FROM || version) || !/^\d{4}-\d{2}-\d{2}$/.test(version) || !Array.isArray(notice.en) || !Array.isArray(notice.ar)) throw new Error("unexpected notice shape");
const out = `// GENERATED by scripts/sync-privacy-notice.mjs from the booking app's Privacy Notice
// (MicromobilityRentalsSystem app.src.html). Do not edit here: change it in the booking app and
// run the script again, so the two never disagree.
export type NoticeBlock = { h?: string; p?: string; ul?: string[]; table?: { head: string[]; rows: string[][] } };
export const PRIVACY_VERSION = ${JSON.stringify(version)};
// The last version riders must confirm: an account that confirmed it or any later one is not asked again.
export const PRIVACY_ASK_FROM = ${JSON.stringify(askFrom)};
export const PRIVACY_NOTICE: { en: NoticeBlock[]; ar: NoticeBlock[] } = ${JSON.stringify({ en: notice.en, ar: notice.ar }, null, 1)};
`;
fs.writeFileSync(new URL("../src/content/privacy-notice.ts", import.meta.url), out);
console.log(`privacy notice ${version}: ${notice.en.length} English and ${notice.ar.length} Arabic blocks`);

// The nationality list: [ISO code, the English name the app stores], every country but Israel.
const line = (name) => {
  const m = new RegExp(`^const ${name}=(.*);$`, "m").exec(src);
  if (!m) throw new Error(`${name} not found in ` + process.argv[2]);
  return vm.runInNewContext(`(${m[1]})`);
};
const nats = line("NATIONALITIES"), countryAr = line("COUNTRY_AR");
if (!Array.isArray(nats) || nats.length < 150 || nats.some((n) => !/^[A-Z]{2}$/.test(n[0]) || typeof n[1] !== "string")) throw new Error("unexpected NATIONALITIES shape");
fs.writeFileSync(new URL("../src/content/nationalities.ts", import.meta.url), `// GENERATED by scripts/sync-privacy-notice.mjs from the booking app's NATIONALITIES and COUNTRY_AR
// (MicromobilityRentalsSystem app.src.html). Do not edit here. A nationality is stored as its English
// name, as the app stores it; its label is the browser's own name for the region in the page's
// language, and for Arabic the app's own where it has one.
export const NATIONALITIES: readonly (readonly [string, string])[] = ${JSON.stringify(nats)};
export const COUNTRY_AR: Readonly<Record<string, string>> = ${JSON.stringify(countryAr)};
`);
console.log(`nationalities: ${nats.length}, Arabic names: ${Object.keys(countryAr).length}`);

// The calling codes: [+code, ISO code, English name], the Gulf's six first (Saudi Arabia at the top),
// as the app lists them; every country but Israel.
const ccAt = src.indexOf("const COUNTRY_CODES=[");
if (ccAt < 0) throw new Error("COUNTRY_CODES not found in " + process.argv[2]);
let depth = 0, end = ccAt + "const COUNTRY_CODES=".length, quote = null;
for (; end < src.length; end++) {
  const c = src[end];
  if (quote) { if (c === "\\") { end++; continue; } if (c === quote) quote = null; continue; }
  if (c === "'" || c === '"' || c === "`") { quote = c; continue; }
  if (c === "[") depth++;
  else if (c === "]" && --depth === 0) break;
}
const codes = vm.runInNewContext("(" + src.slice(ccAt + "const COUNTRY_CODES=".length, end + 1) + ")");
if (!Array.isArray(codes) || codes.length < 150 || codes[0][1] !== "SA" || codes.some((c) => !/^\+\d{1,4}$/.test(c[0]) || !/^[A-Z]{2}$/.test(c[1]) || c[1] === "IL" || /israel/i.test(c[2]))) throw new Error("unexpected COUNTRY_CODES shape");
fs.writeFileSync(new URL("../src/content/dial-codes.ts", import.meta.url), `// GENERATED by scripts/sync-privacy-notice.mjs from the booking app's COUNTRY_CODES
// (MicromobilityRentalsSystem app.src.html). Do not edit here. [+code, ISO code, English name]: the
// Gulf's six first, Saudi Arabia at the top, then the rest; never Israel (the owner's rule).
export const DIAL_CODES: readonly (readonly [string, string, string])[] = ${JSON.stringify(codes)};
`);
console.log(`calling codes: ${codes.length}`);
